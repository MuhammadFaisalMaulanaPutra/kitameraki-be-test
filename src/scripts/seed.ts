import { loadConfig } from '../config/env';
import { createContainer } from '../container';
import { logger } from '../utils/logger';
import { retry } from '../utils/retry';
import { createTaskSchema } from '../validators/task.validator';

/** Organization used by the front-end out of the box (see frontend/.env.example). */
const ORGANIZATION_ID = process.env.SEED_ORGANIZATION_ID ?? '5f0c9d4e-8a3b-4c2d-9e1f-7a6b5c4d3e2f';
const force = process.argv.includes('--force');

const titles = [
  'Set up CI pipeline',
  'Design login page',
  'Write API documentation',
  'Fix pagination bug',
  'Review pull request #42',
  'Prepare sprint demo',
  'Update dependencies',
  'Plan Q1 roadmap',
  'Customer feedback analysis',
  'Optimize Cosmos DB queries',
  'Refactor task service',
  'Add unit tests for validators',
];
const statuses = ['todo', 'in-progress', 'completed'];
const priorities = ['low', 'medium', 'high'];
const tagPool = ['frontend', 'backend', 'devops', 'docs', 'urgent', 'research'];

async function seed(): Promise<void> {
  const container = createContainer(loadConfig());
  await retry(() => container.initialize(), {
    retries: 10,
    delayMs: 3000,
    label: 'Cosmos DB / Blob Storage initialization',
  });

  const existing = await container.services.task.listTasks(ORGANIZATION_ID, {
    page: 1,
    pageSize: 1,
    sortBy: 'createdAt',
    sortOrder: 'desc',
  });

  if (existing.meta.totalItems > 0 && !force) {
    logger.info(
      `Organization already has ${existing.meta.totalItems} task(s); skipping seed (use --force to add more).`,
    );
    container.dispose();
    return;
  }

  const now = Date.now();
  for (const [index, title] of titles.entries()) {
    const input = createTaskSchema.parse({
      title,
      description: `Sample task #${index + 1} generated by the seed script.`,
      dueDate: new Date(now + (index - 3) * 86_400_000).toISOString(),
      priority: priorities[index % priorities.length],
      status: statuses[index % statuses.length],
      tags: [tagPool[index % tagPool.length], tagPool[(index + 2) % tagPool.length]],
    });
    await container.services.task.createTask(ORGANIZATION_ID, input);
  }

  logger.info(`Seeded ${titles.length} tasks for organization ${ORGANIZATION_ID}.`);
  container.dispose();
}

seed().catch((error) => {
  logger.error('Seeding failed', error);
  process.exit(1);
});
